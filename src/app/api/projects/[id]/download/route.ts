import { zipSync, strToU8, type Zippable } from "fflate";
import { NextResponse, type NextRequest } from "next/server";
import { loadProject } from "@/lib/pipeline/runner";
import { isProjectId } from "@/lib/storage/projects";
import { collectProjectFiles } from "@/lib/xcode/build";

/** Downloads a version's complete Xcode project as a .zip (GET ?version=N). */
export async function GET(req: NextRequest, ctx: RouteContext<"/api/projects/[id]/download">) {
  const { id } = await ctx.params;
  const project = isProjectId(id) ? await loadProject(id) : null;
  if (!project) return NextResponse.json({ error: "Project not found" }, { status: 404 });
  const n = Number(req.nextUrl.searchParams.get("version"));
  const version = project.versions.find((v) => v.number === n);
  if (!version?.files.length) return NextResponse.json({ error: "This version has no generated project" }, { status: 400 });

  const name = (version.spec?.appName ?? project.name).replace(/[^A-Za-z0-9 _-]/g, "").trim().replace(/\s+/g, "-") || "GeneratedApp";
  const folder = `${name}-v${version.number}`;
  const tree: Zippable = {};
  for (const f of await collectProjectFiles(id, version.number)) tree[`${folder}/${f.path}`] = new Uint8Array(f.data);

  const models = [...new Set(version.modelCalls.map((c) => c.model))].join(", ");
  tree[`${folder}/README.txt`] = strToU8(
    [
      `${version.spec?.appName ?? project.name} — version ${version.number} (${project.platform})`,
      "",
      "Generated by UI Evolution Engine.",
      `Models: ${models || "n/a"}${version.assets?.length ? ", muse-image-1.0" : ""}`,
      `Build: ${version.build?.status ?? "not built"}`,
      `Created: ${version.createdAt}`,
      "",
      "Open GeneratedApp.xcodeproj in Xcode 16 or later and press Run.",
      project.platform === "iOS" ? "Pick an iPhone simulator as the run destination." : "Run destination: My Mac.",
      "",
      "Request:",
      project.prompt,
      version.instruction ? `\nIteration instruction:\n${version.instruction}` : "",
    ].join("\n"),
  );

  const zip = zipSync(tree, { level: 6 });
  return new NextResponse(new Uint8Array(zip), {
    headers: {
      "Content-Type": "application/zip",
      "Content-Disposition": `attachment; filename="${folder}.zip"`,
      "Cache-Control": "no-store",
    },
  });
}
